export function updateSeoKeyword(id: string, updates: Partial<SeoKeywordItem>): SeoKeywordItem | null {
  const index = SEO_KEYWORDS_MATRIX.findIndex(k => k.id === id);
  if (index === -1) return null;
  SEO_KEYWORDS_MATRIX[index] = {
    ...SEO_KEYWORDS_MATRIX[index],
    ...updates,
    id: SEO_KEYWORDS_MATRIX[index].id,
  };
  return SEO_KEYWORDS_MATRIX[index];
}

export function addSeoKeywords(items: Array<Omit<SeoKeywordItem, 'id'>>): SeoKeywordItem[] {
  const newItems: SeoKeywordItem[] = items.map((item, idx) => ({
    ...item,
    id: `kw-${Date.now()}-${idx}-${Math.random().toString(36).substring(2, 6)}`,
  }));
  SEO_KEYWORDS_MATRIX.push(...newItems);
  return newItems;
}

export function generateCsvExport(): string {
  const headers = ['ID', 'Mot-clé', 'Intention', 'Priorité', 'Page cible', 'Slug URL', 'Titre SEO', 'H1', 'CTA', 'Statut', 'Silo', 'Zone'];
  const rows = SEO_KEYWORDS_MATRIX.map(item => [
    `"${item.id}"`,
    `"${(item.keyword || '').replace(/"/g, '""')}"`,
    `"${item.intent || ''}"`,
    `"${item.priority || ''}"`,
    `"${(item.targetPage || '').replace(/"/g, '""')}"`,
    `"${item.slug || ''}"`,
    `"${(item.title || '').replace(/"/g, '""')}"`,
    `"${(item.h1 || '').replace(/"/g, '""')}"`,
    `"${(item.cta || '').replace(/"/g, '""')}"`,
    `"${item.status || ''}"`,
    `"${item.serviceType || ''}"`,
    `"${item.geo || ''}"`
  ].join(','));
  return [headers.join(','), ...rows].join('\n');
}

